using NHibernate.Mapping.ByCode;
using NHibernate.Mapping.ByCode.Conformist;

namespace DapperNHibernateApi.NHibernateData;

// ---------------------------------------------------------------------------
// NHibernate MAPPINGS (mapping-by-code style).
// These tell NHibernate how each class matches a table - the same job that
// OnModelCreating / Fluent API does in EF Core.
// ---------------------------------------------------------------------------

public class NhDepartmentMap : ClassMapping<NhDepartment>
{
    public NhDepartmentMap()
    {
        Table("Departments");

        // Primary key, generated by SQL Server IDENTITY
        Id(x => x.Id, m => m.Generator(Generators.Identity));

        Property(x => x.Name, m =>
        {
            m.NotNullable(true);
            m.Length(100);
        });
        Property(x => x.Location, m => m.Length(100));

        // ONE-TO-MANY: one department -> many employees, linked by Employees.DepartmentId
        Bag(x => x.Employees,
            collection =>
            {
                collection.Key(k => k.Column("DepartmentId"));
                collection.Inverse(true); // the Employee side owns the foreign key
            },
            relation => relation.OneToMany());
    }
}

public class NhEmployeeMap : ClassMapping<NhEmployee>
{
    public NhEmployeeMap()
    {
        Table("Employees");

        Id(x => x.Id, m => m.Generator(Generators.Identity));

        // Column names default to the property names
        Property(x => x.FirstName);
        Property(x => x.LastName);
        Property(x => x.Email);
        Property(x => x.Salary);
        Property(x => x.HireDate);

        // MANY-TO-ONE: each employee -> one department, via the DepartmentId column
        ManyToOne(x => x.Department, m =>
        {
            m.Column("DepartmentId");
            m.NotNullable(true);
        });
    }
}
